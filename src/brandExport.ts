import { createHash } from 'node:crypto';
import { BRAND } from './brand';
import { BRAND_TOKENS, HEX, type BrandTokens } from './brandTokens';

export interface TokenFile {
  schema: 1;
  name: string;
  version: string;
  colour: Record<string, string>;
  font: Record<string, { family: string; stack: string }>;
  radius: Record<string, string>;
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value !== null && typeof value === 'object') {
    const src = value as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(src).sort()) out[k] = sortKeys(src[k]);
    return out;
  }
  return value;
}

/** Deterministic JSON: keys sorted at every level, two-space indent, LF, exactly one trailing newline. */
export function canonicalJson(value: unknown): string {
  return `${JSON.stringify(sortKeys(value), null, 2)}\n`;
}

/** First 16 hex characters of the SHA-256 of the canonical JSON of the tokens. */
export function tokenVersion(t: BrandTokens): string {
  return createHash('sha256').update(canonicalJson(t)).digest('hex').slice(0, 16);
}

const FORBIDDEN_STACK = /[;{}\n\r]/;

export function buildTokenFile(t: BrandTokens = BRAND_TOKENS): TokenFile {
  for (const [role, value] of Object.entries(t.colour)) {
    if (!HEX.test(value)) throw new Error(`Invalid colour for role "${role}": ${JSON.stringify(value)} is not a 6-digit hex colour`);
  }
  for (const [name, f] of Object.entries(t.font)) {
    if (FORBIDDEN_STACK.test(f.stack)) throw new Error(`Invalid font stack for "${name}": must not contain ";", "{", "}" or a newline`);
  }
  return {
    schema: 1,
    name: BRAND.name,
    version: tokenVersion(t),
    colour: { ...t.colour },
    font: { display: { ...t.font.display }, body: { ...t.font.body }, mono: { ...t.font.mono } },
    radius: { ...t.radius },
  };
}

const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const COLOUR_ORDER = [
  'bg', 'surface', 'surfaceRaised', 'border', 'borderStrong',
  'text', 'textSoft', 'textMuted', 'textSubtle',
  'primary', 'primaryText', 'accent', 'highlight', 'success', 'danger',
] as const;
const FONT_ORDER = ['display', 'body', 'mono'] as const;

export function renderCss(file: TokenFile): string {
  const lines: string[] = [
    `/* Generated by npm run brand:export from src/brandTokens.ts. Do not edit by hand. version: ${file.version} */`,
    ':root {',
  ];
  for (const role of COLOUR_ORDER) lines.push(`  --iai-${kebab(role)}: ${file.colour[role]};`);
  for (const f of FONT_ORDER) lines.push(`  --iai-font-${f}: ${file.font[f].stack};`);
  lines.push(`  --iai-radius-card: ${file.radius.card};`);
  lines.push('}', '');
  return lines.join('\n');
}

/** Weights match the Google Fonts link in index.html. */
export function renderFontsManifest(): string {
  const licence = 'SIL Open Font License 1.1';
  const source = 'Google Fonts';
  const entry = (role: string, family: string, weights: number[]) => ({ role, family, licence, source, selfHosted: false, weights });
  return canonicalJson({
    schema: 1,
    fonts: [
      entry('display', BRAND_TOKENS.font.display.family, [500, 600, 700]),
      entry('body', BRAND_TOKENS.font.body.family, [400, 500, 600, 700]),
      entry('mono', BRAND_TOKENS.font.mono.family, [400, 700]),
    ],
  });
}

function luminance(hex: string): number {
  if (!HEX.test(hex)) throw new Error(`Invalid colour: ${JSON.stringify(hex)} is not a 6-digit hex colour`);
  const channel = (i: number): number => {
    const c = parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(0) + 0.7152 * channel(1) + 0.0722 * channel(2);
}

/** WCAG 2.x contrast ratio between two 6-digit hex colours. */
export function contrastRatio(foreground: string, background: string): number {
  const a = luminance(foreground);
  const b = luminance(background);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

/** True when a generated file is missing or differs from the expected text. Only CRLF is normalised, so Windows checkouts pass. */
export function outOfDate(onDisk: string | undefined, expected: string): boolean {
  if (onDisk === undefined) return true;
  return onDisk.replace(/\r\n/g, '\n') !== expected;
}
