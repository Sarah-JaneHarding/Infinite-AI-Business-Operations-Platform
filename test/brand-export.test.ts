import { describe, expect, it } from 'vitest';
import { BRAND } from '../src/brand';
import { BRAND_TOKENS, type BrandTokens } from '../src/brandTokens';
import {
  buildTokenFile,
  canonicalJson,
  contrastRatio,
  outOfDate,
  renderCss,
  renderFontsManifest,
  tokenVersion,
} from '../src/brandExport';

const clone = (): BrandTokens => structuredClone(BRAND_TOKENS);

describe('canonicalJson', () => {
  it('sorts keys at every level with two-space indent and one trailing newline', () => {
    expect(canonicalJson({ b: 1, a: { d: 2, c: 3 } })).toBe('{\n  "a": {\n    "c": 3,\n    "d": 2\n  },\n  "b": 1\n}\n');
  });
});

describe('tokenVersion', () => {
  it('is 16 hex characters, stable, and sensitive to a change', () => {
    const v = tokenVersion(BRAND_TOKENS);
    expect(v).toMatch(/^[0-9a-f]{16}$/);
    expect(tokenVersion(BRAND_TOKENS)).toBe(v);
    const changed = clone();
    changed.colour.primary = '#000000';
    expect(tokenVersion(changed)).not.toBe(v);
  });
});

describe('buildTokenFile', () => {
  it('builds the token file from the brand tokens', () => {
    const f = buildTokenFile();
    expect(f.schema).toBe(1);
    expect(f.name).toBe('Infinite-AI');
    expect(Object.keys(f.colour)).toHaveLength(15);
    expect(Object.keys(f.font).sort()).toEqual(['body', 'display', 'mono']);
    expect(f.radius.card).toBe(BRAND_TOKENS.radius.card);
    expect(f.version).toBe(tokenVersion(BRAND_TOKENS));
  });

  it('contains no contact or founder details', () => {
    const json = JSON.stringify(buildTokenFile());
    for (const s of [BRAND.email, BRAND.phone, BRAND.address.street, BRAND.founder.name]) {
      expect(json).not.toContain(s);
    }
  });

  it('throws naming the role for an invalid colour', () => {
    const a = clone();
    a.colour.primary = 'red';
    expect(() => buildTokenFile(a)).toThrow(/primary/);
    const b = clone();
    b.colour.danger = '#12345';
    expect(() => buildTokenFile(b)).toThrow(/danger/);
  });

  it('throws naming the radius key for a value that is not a length', () => {
    for (const bad of ['14', '14px;', '', '14 px', 'px', '-1px', '14em', '1.px']) {
      const t = clone();
      t.radius.card = bad;
      expect(() => buildTokenFile(t), JSON.stringify(bad)).toThrow(/radius for "card"/);
    }
  });

  it('accepts px and rem radii', () => {
    for (const ok of ['14px', '0.5rem', '0px', '1.25rem']) {
      const t = clone();
      t.radius.card = ok;
      expect(buildTokenFile(t).radius.card).toBe(ok);
    }
  });

  it('throws naming the font for a stack with a forbidden character', () => {
    for (const bad of ['a;b', 'a{b', 'a}b', 'a\nb']) {
      const t = clone();
      t.font.mono.stack = bad;
      expect(() => buildTokenFile(t)).toThrow(/mono/);
    }
  });
});

describe('renderCss', () => {
  const css = renderCss(buildTokenFile());
  it('starts with the generated-file comment carrying the version', () => {
    expect(css.startsWith('/* Generated by npm run brand:export from src/brandTokens.ts. Do not edit by hand. version: ')).toBe(true);
    expect(css).toContain(`version: ${tokenVersion(BRAND_TOKENS)} */`);
  });
  it('declares the variables with token values in one :root block', () => {
    expect(css).toContain('--iai-bg: #05070F;');
    expect(css).toContain('--iai-primary: #5BC8EC;');
    expect(css).toContain(`--iai-font-display: ${BRAND_TOKENS.font.display.stack};`);
    expect(css).toContain("'Space Grotesk'");
    expect(css).toContain('--iai-radius-card: 14px;');
    expect(css.match(/:root/g)).toHaveLength(1);
    expect(css.endsWith('\n')).toBe(true);
    expect(css).not.toContain('\r');
  });
  it('keeps the listed variable order', () => {
    const names = [...css.matchAll(/(--iai-[a-z-]+):/g)].map((m) => m[1]);
    expect(names).toEqual([
      '--iai-bg', '--iai-surface', '--iai-surface-raised', '--iai-border', '--iai-border-strong',
      '--iai-text', '--iai-text-soft', '--iai-text-muted', '--iai-text-subtle',
      '--iai-primary', '--iai-primary-text', '--iai-accent', '--iai-highlight', '--iai-success', '--iai-danger',
      '--iai-font-display', '--iai-font-body', '--iai-font-mono', '--iai-radius-card',
    ]);
  });
});

describe('the CSS carries everything the JSON carries', () => {
  const file = buildTokenFile();
  const css = renderCss(file);
  const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  const declared = new Map([...css.matchAll(/(--iai-[a-z-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2]]));

  it('has one --iai- colour variable per JSON colour key, no more and no fewer', () => {
    const colourVars = [...declared.keys()].filter((n) => !n.startsWith('--iai-font-') && n !== '--iai-radius-card').sort();
    expect(colourVars).toEqual(Object.keys(file.colour).map((k) => `--iai-${kebab(k)}`).sort());
  });
  it('gives each colour variable the JSON value', () => {
    for (const [role, value] of Object.entries(file.colour)) expect(declared.get(`--iai-${kebab(role)}`)).toBe(value);
  });
  it('carries the radius and the three font stacks', () => {
    expect(declared.get('--iai-radius-card')).toBe(file.radius.card);
    for (const name of ['display', 'body', 'mono']) expect(declared.get(`--iai-font-${name}`)).toBe(file.font[name].stack);
  });
});

describe('contrastRatio', () => {
  it('is 21 for black on white and 1 for identical colours', () => {
    expect(contrastRatio('#000000', '#FFFFFF')).toBeCloseTo(21, 2);
    expect(contrastRatio('#FFFFFF', '#FFFFFF')).toBeCloseTo(1, 5);
  });
  it('does not depend on argument order', () => {
    expect(contrastRatio('#5BC8EC', '#05070F')).toBeCloseTo(contrastRatio('#05070F', '#5BC8EC'), 10);
  });
  it('throws for an invalid colour', () => {
    expect(() => contrastRatio('red', '#FFFFFF')).toThrow();
  });
});

describe('renderFontsManifest', () => {
  it('lists Space Grotesk, Inter and Space Mono, not self-hosted', () => {
    const m = JSON.parse(renderFontsManifest()) as { schema: number; fonts: { role: string; family: string; selfHosted: boolean; weights: number[] }[] };
    expect(m.schema).toBe(1);
    expect(m.fonts.map((f) => f.family).sort()).toEqual(['Inter', 'Space Grotesk', 'Space Mono']);
    expect(m.fonts.every((f) => f.selfHosted === false)).toBe(true);
    expect(m.fonts.find((f) => f.role === 'display')?.weights).toEqual([500, 600, 700]);
    expect(m.fonts.find((f) => f.role === 'body')?.weights).toEqual([400, 500, 600, 700]);
    expect(m.fonts.find((f) => f.role === 'mono')?.weights).toEqual([400, 700]);
  });
});

describe('canonicalJson edge cases', () => {
  it('keeps array order but sorts keys of objects inside arrays', () => {
    expect(canonicalJson({ l: [{ b: 1, a: 2 }, 'z', 'a'] })).toBe('{\n  "l": [\n    {\n      "a": 2,\n      "b": 1\n    },\n    "z",\n    "a"\n  ]\n}\n');
  });
  it('round-trips unicode unescaped', () => {
    const out = canonicalJson({ k: 'é·→' });
    expect(out).toContain('"é·→"');
    expect(out).not.toContain('\\u');
  });
  it('renders nested empty object and array compactly', () => {
    expect(canonicalJson({ a: {}, b: [] })).toBe('{\n  "a": {},\n  "b": []\n}\n');
  });
});

describe('outOfDate', () => {
  const x = 'a: 1\nb: 2\n';
  it('treats a missing file as out of date', () => {
    expect(outOfDate(undefined, x)).toBe(true);
  });
  it('is false for identical text', () => {
    expect(outOfDate(x, x)).toBe(false);
  });
  it('tolerates CRLF line endings', () => {
    expect(outOfDate(x.replace(/\n/g, '\r\n'), x)).toBe(false);
  });
  it('still detects a value change when line endings also differ', () => {
    expect(outOfDate('a: 1\r\nb: 3\r\n', x)).toBe(true);
  });
  it('detects a trailing space', () => {
    expect(outOfDate('a: 1 \nb: 2\n', x)).toBe(true);
  });
  it('detects a missing final newline', () => {
    expect(outOfDate('a: 1\nb: 2', x)).toBe(true);
  });
  it('detects a lone CR inside a line', () => {
    expect(outOfDate('a: 1\rb: 2\n', x)).toBe(true);
  });
});
